import assert from 'node:assert/strict';
import { normOffsets, when } from '../src/notify.js';
assert.deepEqual(normOffsets([[0, 16], [1, 12]]), ['same', 'day'], 'gamle par oversettes');
assert.deepEqual(normOffsets([[2, 12], [7, 12]]), ['same', 'day'], 'fjernede valg gir standard');
assert.deepEqual(normOffsets(['mon']), ['same', 'day'], 'mandag er fjernet: bare mandag gir standard');
assert.deepEqual(normOffsets(['mon', 'day', 'day', 'x']), ['day'], 'mandag, duplikater og ukjent forkastes');
assert.deepEqual(normOffsets(undefined), ['same', 'day']);
assert.deepEqual(when({ date: '2026-10-15' }, 'same'), [0, 16], 'samme dag kl 16');
assert.deepEqual(when({ date: '2026-10-15', time: '20:00' }, 'same'), [0, 16], 'senere start: fortsatt kl 16');
assert.deepEqual(when({ date: '2026-10-15', time: '15:00' }, 'same'), [0, 12], 'tidlig start: tre timer før');
assert.deepEqual(when({ date: '2026-10-15', time: '01:00' }, 'same'), [0, 0], 'aldri negativ time');
assert.deepEqual(when({ date: '2026-10-15' }, 'day'), [1, 12], 'dagen før kl 12');
console.log('ok: varsellogikk');
